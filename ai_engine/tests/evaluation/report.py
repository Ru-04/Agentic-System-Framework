"""Write the AI-S10 catalogue and result files from the runner, so no count is typed by hand.

Usage, from the ai_engine directory with PYTHONPATH set to ``src;tests``::

    python -m evaluation.report <output_dir> <commit_label>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from evaluation.catalog import build_catalog
from evaluation.runner import run_catalog, summarise, to_json, to_markdown
from evaluation.scenarios import build_executors


def _cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: python -m evaluation.report <output_dir> <commit_label>", file=sys.stderr)
        return 2
    output = Path(argv[1])
    commit = argv[2]
    catalog = build_catalog()
    results = run_catalog(catalog, build_executors())
    summary = summarise(results)

    lines = [
        "# AI-S10 Master Scenario Catalogue",
        "",
        "Generated by `python -m evaluation.report` from `ai_engine/tests/evaluation/catalog.py`. "
        "Do not edit by hand; regenerate instead.",
        "",
        f"Scenarios: {summary['total_scenarios']}. Outcomes: {summary['by_outcome']}.",
        "",
        "| ID | Classification | Area | Status | Severity | Expected | Dependency | References |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for scenario in sorted(catalog, key=lambda s: s.scenario_id):
        refs = ", ".join(scenario.references)
        lines.append(
            f"| {scenario.scenario_id} | {scenario.classification.value} | {scenario.area} | "
            f"{scenario.status.value} | {scenario.severity} | {_cell(scenario.expected)} | "
            f"{_cell(scenario.dependency)} | {_cell(refs)} |"
        )
    output.mkdir(parents=True, exist_ok=True)
    (output / "AI_S10_MASTER_SCENARIO_CATALOG.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
    (output / "AI_S10_EVALUATION_RESULTS.md").write_text(
        to_markdown(results, commit), encoding="utf-8"
    )
    (output / "AI_S10_EVALUATION_RESULTS.json").write_text(
        to_json(results, commit) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
