"""Write the AI-S10 catalogue and result files from the runner, so no count is typed by hand.

Usage, from the ai_engine directory with PYTHONPATH set to ``src;tests``::

    python -m evaluation.report <output_dir>

The candidate is identified by a digest of the evaluated source, not by a label, so an export of the
same commit reproduces the same digest and the same results.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from evaluation.catalog import build_catalog
from evaluation.executors import build_executors
from evaluation.runner import run_catalog, summarise, to_json, to_markdown

ENGINE_ROOT = Path(__file__).resolve().parents[2]
BASE_COMMIT = "211d308"


def _digest_inputs() -> list[Path]:
    """Every file that determines the evaluation: the engine source and the AI-S10 test package."""
    paths = list((ENGINE_ROOT / "src").rglob("*.py"))
    paths += list((ENGINE_ROOT / "tests" / "evaluation").glob("*.py"))
    paths += list((ENGINE_ROOT / "tests").glob("test_ai_s10_*.py"))
    return sorted(paths, key=lambda p: p.relative_to(ENGINE_ROOT).as_posix())


def candidate_digest() -> str:
    """SHA-256 over the relative path and normalised text of every evaluated file."""
    digest = hashlib.sha256()
    for path in _digest_inputs():
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        digest.update(path.relative_to(ENGINE_ROOT).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(text.encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()


def candidate_label() -> str:
    return f"base {BASE_COMMIT}; evaluated source sha256 {candidate_digest()}"


def _cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m evaluation.report <output_dir>", file=sys.stderr)
        return 2
    output = Path(argv[1])
    label = candidate_label()
    catalog = build_catalog()
    results = run_catalog(catalog, build_executors())
    summary = summarise(results)

    lines = [
        "# AI-S10 Master Scenario Catalogue",
        "",
        "Generated by `python -m evaluation.report` from `ai_engine/tests/evaluation/catalog.py`. "
        "Do not edit by hand; regenerate instead.",
        "",
        f"Candidate: `{label}`",
        "",
        f"Scenarios: {summary['total_scenarios']}. Outcomes: {summary['by_outcome']}.",
        "",
        "| ID | Classification | Area | Status | Severity | Enforcement | Expected | Dependency |"
        " References |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for scenario in sorted(catalog, key=lambda s: s.scenario_id):
        refs = ", ".join(scenario.references)
        lines.append(
            f"| {scenario.scenario_id} | {scenario.classification.value} | {scenario.area} | "
            f"{scenario.status.value} | {scenario.severity} | {scenario.enforcement or '-'} | "
            f"{_cell(scenario.expected)} | {_cell(scenario.dependency)} | {_cell(refs)} |"
        )
    output.mkdir(parents=True, exist_ok=True)
    (output / "AI_S10_MASTER_SCENARIO_CATALOG.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
    (output / "AI_S10_EVALUATION_RESULTS.md").write_text(
        to_markdown(results, label), encoding="utf-8"
    )
    (output / "AI_S10_EVALUATION_RESULTS.json").write_text(
        to_json(results, label) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
